import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import {
  autoConnectProvider,
  isAllowedCachedUrl,
  manualEntryAllowed,
  startsWithManualEntry,
} from "../src/lib/line/provider-flow.ts";
import {
  ProviderConfigError,
  renderProviderTs,
  validateConfigUrl,
  validateProviders,
} from "../scripts/provider-config.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const read = (rel: string) => readFileSync(path.join(ROOT, rel), "utf8");

const entry = (over: Record<string, unknown> = {}) => ({
  id: "demo",
  name: "Demo Project",
  config_url: "https://example.com/config.json",
  ...over,
});

function rejects(input: unknown, fragment: string | RegExp) {
  assert.throws(
    () => validateProviders(input),
    (error: unknown) => {
      assert.ok(error instanceof ProviderConfigError);
      const message = (error as Error).message;
      if (typeof fragment === "string")
        assert.ok(message.includes(fragment), message);
      else assert.match(message, fragment);
      return true;
    },
  );
}

test("the shipped provider file builds and keeps manual entry available", () => {
  const shipped = JSON.parse(read("branding/provider.json"));
  const validated = validateProviders(shipped);
  // The repo builds a universal launcher; forks bake their own addresses.
  assert.equal(validated.providers.length, 0);
  assert.equal(validated.allowManualUrl, true);
  // Generated output must be in sync with the source file.
  const generated = read("src/brand/providers.generated.ts");
  assert.equal(generated, renderProviderTs(validated));
});

test("a baked provider is normalised and rendered for the bundle", () => {
  const validated = validateProviders({
    allow_manual_url: false,
    providers: [entry({ config_url: "  https://example.com/config.json  " })],
  });
  assert.equal(validated.allowManualUrl, false);
  assert.deepEqual(validated.providers, [
    {
      id: "demo",
      name: "Demo Project",
      configUrl: "https://example.com/config.json",
    },
  ]);
  const ts = renderProviderTs(validated);
  assert.match(ts, /allowManualUrl: false/);
  assert.ok(ts.includes('"https://example.com/config.json"'));
  assert.match(ts, /GENERATED by npm run brand/);
  // A name with a quote must not break out of the generated string literal.
  const quoted = renderProviderTs(
    validateProviders({ providers: [entry({ name: 'a"b\\c' })] }),
  );
  assert.ok(quoted.includes(JSON.stringify('a"b\\c')));
});

test("plaintext, credentialed and fragmented endpoints cannot be baked in", () => {
  for (const url of [
    "http://example.com/config.json",
    "ftp://example.com/config.json",
    "file:///etc/passwd",
    "javascript:alert(1)",
    "https://user:pass@example.com/config.json",
    "https://example.com/config.json#fragment",
    "not a url",
    "",
  ]) {
    assert.throws(
      () => validateConfigUrl("config_url", url),
      ProviderConfigError,
      `accepted ${url}`,
    );
  }
  assert.throws(
    () =>
      validateConfigUrl(
        "config_url",
        `https://example.com/${"a".repeat(2100)}`,
      ),
    /2048/,
  );
  assert.equal(
    validateConfigUrl("config_url", "https://example.com/config.json"),
    "https://example.com/config.json",
  );
});

test("an unreachable build is refused instead of shipped", () => {
  // No providers AND no manual entry = a launcher nobody can connect with.
  rejects({ allow_manual_url: false, providers: [] }, "no way to connect");
  rejects({ providers: [] }, "no way to connect");
  // Explicitly opting into manual entry makes the same file valid.
  assert.equal(
    validateProviders({ allow_manual_url: true, providers: [] }).allowManualUrl,
    true,
  );
});

test("duplicates, unknown keys and bad slugs fail the build", () => {
  rejects(
    { providers: [entry(), entry({ id: "other" })] },
    "duplicate config_url",
  );
  rejects(
    { providers: [entry(), entry({ config_url: "https://b.test/c.json" })] },
    "duplicate provider id",
  );
  rejects({ providers: [entry({ id: "../evil" })] }, "lowercase slug");
  rejects({ providers: [entry({ id: "A" })] }, "lowercase slug");
  rejects(
    { providers: [entry({ redirect: "https://evil.test" })] },
    "unknown key",
  );
  rejects({ providers: [entry({ name: "   " })] }, "1..100");
  rejects(
    { providers: [entry({ name: "bad\u0000name" })] },
    "control characters",
  );
  rejects({ providers: [entry({ name: "x".repeat(101) })] }, "1..100");
  rejects({ providers: "nope" }, "must be an array");
  rejects(
    { allow_manual_url: "yes", providers: [entry()] },
    "must be a boolean",
  );
  rejects(null, "must be an object");
  rejects(
    {
      providers: Array.from({ length: 21 }, (_, i) =>
        entry({ id: `p${i}`, config_url: `https://e.test/${i}.json` }),
      ),
    },
    "at most 20",
  );
});

test("a locked build connects by itself and never offers a URL field", () => {
  const one = validateProviders({ providers: [entry()] });
  assert.equal(startsWithManualEntry(one), false);
  assert.equal(manualEntryAllowed(one), false);
  assert.equal(
    autoConnectProvider(one)?.configUrl,
    "https://example.com/config.json",
  );

  const two = validateProviders({
    providers: [
      entry(),
      entry({ id: "b", config_url: "https://b.test/c.json" }),
    ],
  });
  assert.equal(startsWithManualEntry(two), false);
  // Two providers means the player picks; nothing connects behind their back.
  assert.equal(autoConnectProvider(two), undefined);

  const open = validateProviders({
    allow_manual_url: true,
    providers: [entry()],
  });
  assert.equal(manualEntryAllowed(open), true);
  // Even when manual entry is allowed, a baked build does not start on it.
  assert.equal(startsWithManualEntry(open), false);

  const universal = validateProviders({
    allow_manual_url: true,
    providers: [],
  });
  assert.equal(startsWithManualEntry(universal), true);
  assert.equal(manualEntryAllowed(universal), true);
  assert.equal(autoConnectProvider(universal), undefined);
});

test("a locked build refuses a cached config from another provider", () => {
  const locked = validateProviders({ providers: [entry()] });
  assert.equal(
    isAllowedCachedUrl(locked, "https://example.com/config.json"),
    true,
  );
  // Trailing slash and whitespace are not a different provider.
  assert.equal(
    isAllowedCachedUrl(locked, "  https://example.com/config.json/  "),
    true,
  );
  assert.equal(
    isAllowedCachedUrl(locked, "https://evil.test/config.json"),
    false,
  );
  assert.equal(
    isAllowedCachedUrl(locked, "http://example.com/config.json"),
    false,
  );
  assert.equal(isAllowedCachedUrl(locked, ""), false);
  // An open build keeps working with whatever the player connected to before.
  const open = validateProviders({
    allow_manual_url: true,
    providers: [entry()],
  });
  assert.equal(isAllowedCachedUrl(open, "https://other.test/c.json"), true);
});

test("the shell delegates connection decisions to the tested module", () => {
  const shell = read("src/components/line/LineLauncher.tsx");
  assert.match(shell, /bakedProviders/);
  // The picker wins over ConfigUrlInput whenever providers are baked in.
  assert.match(shell, /!manualUrl && bakedProviders\.providers\.length > 0/);
  // The decisions must come from provider-flow.ts, not an inline copy.
  assert.match(shell, /from "@\/lib\/line\/provider-flow"/);
  assert.match(shell, /startsWithManualEntry\(bakedProviders\)/);
  assert.match(shell, /autoConnectProvider\(bakedProviders\)/);
  assert.match(
    shell,
    /if \(!isAllowedCachedUrl\(bakedProviders, cached\.sourceUrl\)\)/,
  );

  const picker = read("src/components/line/ProviderPicker.tsx");
  assert.doesNotMatch(
    picker,
    /<Input|type="url"/,
    "no URL field in the picker",
  );
  assert.match(picker, /allowManualUrl && \(/);
});

test("provider URLs are validated by the same rules as runtime URLs", () => {
  const rust = read("src-tauri/src/line/config.rs");
  const start = rust.indexOf("pub fn validate_https(");
  assert.ok(start > 0, "validate_https must still exist");
  const fn = rust.slice(start, rust.indexOf("\nfn text(", start));
  // If Rust changes its rule set, this test forces the build-time copy to follow.
  assert.match(fn, /https/);
  assert.match(fn, /2048/);
  assert.match(fn, /username|password/);
  assert.match(fn, /fragment/);
});
