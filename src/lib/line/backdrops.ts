import type { GradientConfig } from "hazeglow";

/**
 * Twelve animated themes. Saved ids stay stable and each palette/shape keeps
 * its own character. Grain is consistently 0.443 (matching Copper Bush), while
 * the focal x-coordinate is aligned near the sidebar/content seam at 0.2.
 * Per-theme shade and the shared backdrop wash keep interface text legible.
 */

export interface BackdropTheme {
  id: string;
  /**
   * Russian name, and the only place a theme is named. Other languages are in
   * the message catalogue under `backdrop.<id>`; the picker translates the id,
   * so adding a language never touches this file.
   */
  name: string;
  /**
   * Three colours that read as the theme at thumbnail size, picked from its own
   * palette: the dominant warm, the dominant cool and a mid-tone between them.
   * They paint the preview and the swatch, never anything else.
   */
  swatch: [string, string, string];
  /** Opacity of the legibility veil over the haze. 0 = none, 1 = opaque. */
  shade: number;
  config: GradientConfig;
}

