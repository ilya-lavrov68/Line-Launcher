/**
 * Build-time provider address.
 *
 * A provider builds their own launcher, so there is exactly ONE provider per
 * build. Their servers are not listed here — they arrive in the config that this
 * URL serves. The player never types an address: they register and sign in.
 *
 * Security: the URL is compiled into the binary, so it is held to the same HTTPS
 * rule as a URL typed at runtime (src-tauri/src/line/config.rs). A build must not
 * bake in http://, credentials, or a fragment.
 */

export interface ProviderConfig {
  /** HTTPS URL of the provider's config.json. Empty = template not configured. */
  config_url: string;
}

export class ProviderConfigError extends Error {}

const MAX_URL_LENGTH = 2048;

function fail(message: string): never {
  throw new ProviderConfigError(`[provider] ${message}`);
}

/** Mirrors validate_https in Rust. Kept in sync by tests/provider-config.test.ts. */
export function validateConfigUrl(value: unknown): string {
  if (typeof value !== "string") {
    fail("config_url must be a string with an HTTPS URL");
  }
  const raw = value.trim();
  if (raw.length > MAX_URL_LENGTH)
    fail("config_url is longer than 2048 characters");
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    fail(`config_url is not a valid URL: ${raw}`);
  }
  if (url.protocol !== "https:") {
    fail(
      `config_url must use https:// (got ${url.protocol}). A launcher build ` +
        `cannot ship a plaintext provider endpoint.`,
    );
  }
  if (!url.hostname) fail("config_url must name a host");
  if (url.username || url.password)
    fail("config_url must not embed credentials");
  if (url.hash) fail("config_url must not contain a #fragment");
  return url.toString();
}

export interface ValidatedProvider {
  /** Empty when the template has not been pointed at a project yet. */
  configUrl: string;
}

export function validateProvider(input: unknown): ValidatedProvider {
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    fail("config must be an object");
  }
  const config = input as Record<string, unknown>;
  for (const key of Object.keys(config)) {
    if (key !== "config_url" && key !== "$comment") {
      fail(
        `unknown key "${key}". A build has exactly one provider: set config_url ` +
          `to its config.json. Servers come from that config, not from this file.`,
      );
    }
  }
  if (typeof config.config_url !== "string") {
    fail(
      "config_url is required (use an empty string for an unconfigured template)",
    );
  }
  // An empty value is the shipped template state, not a player-facing option.
  if (!config.config_url.trim()) return { configUrl: "" };
  return { configUrl: validateConfigUrl(config.config_url) };
}

/**
 * Installers must name a provider. Called by scripts/tauri-build.mjs so an
 * unconfigured template can still be developed, but never shipped to players.
 */
export function requireConfigured(config: ValidatedProvider): void {
  if (!config.configUrl) {
    fail(
      "config_url is empty. Set branding/provider.json to your project's " +
        "config.json before building an installer — players must not have to " +
        "enter an address.",
    );
  }
}

export function renderProviderTs(config: ValidatedProvider): string {
  return `/* GENERATED by npm run brand — do not edit by hand.
 * Source: branding/provider.json
 *
 * One provider per build. Their servers come from the config this URL serves.
 * The Rust layer re-validates the URL before use, so this file is a convenience,
 * not a trust boundary.
 */
import type { BakedProvider } from "./provider-types";

export const bakedProvider: BakedProvider = {
  configUrl: ${JSON.stringify(config.configUrl)},
};
`;
}
