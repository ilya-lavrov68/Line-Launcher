const ROOT = path.resolve(import.meta.dirname, "..");
const read = (rel: string) => readFileSync(path.join(ROOT, rel), "utf8");

/** Source-only view: comments explain old behaviour and name old codes. */
function stripComments(text: string) {
  return text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
}

const URL_OK = "https://example.com/line/config.json";

function rejects(input: unknown, fragment: string | RegExp) {
  assert.throws(
    () => validateProvider(input),
    (error: unknown) => {
      assert.ok(error instanceof ProviderConfigError);
      const message = (error as Error).message;
      if (typeof fragment === "string") {
        assert.ok(message.includes(fragment), message);
      } else assert.match(message, fragment);
      return true;
    },
  );
}

test("the shipped template builds and stays unconfigured", () => {
  const shipped = JSON.parse(read("branding/provider.json"));
  const validated = validateProvider(shipped);
  assert.equal(validated.configUrl, "");
  assert.equal(isConfigured(validated), false);
  // Generated output must be in sync with the source file.
  assert.equal(
    read("src/brand/provider.generated.ts"),
    renderProviderTs(validated),
  );
});

test("one provider is baked in verbatim and normalised", () => {
  const validated = validateProvider({ config_url: `  ${URL_OK}  ` });
  assert.deepEqual(validated, { configUrl: URL_OK });
  const ts = renderProviderTs(validated);
  assert.ok(ts.includes(JSON.stringify(URL_OK)));
  assert.match(ts, /export const bakedProvider: BakedProvider/);
  assert.match(ts, /GENERATED by npm run brand/);
  // Exactly one address: no array, no catalogue, no per-provider names.
  assert.doesNotMatch(ts, /providers\s*:/);
  assert.doesNotMatch(ts, /\[\s*\{/);
});

test("a list of providers is rejected, not silently accepted", () => {
  // The old multi-provider shape must fail loudly so a fork migrates instead of
  // silently shipping an unconfigured launcher.
  rejects(
    { providers: [{ id: "a", name: "A", config_url: URL_OK }] },
    "exactly one provider",
  );
  rejects(
    { allow_manual_url: true, config_url: URL_OK },
    "exactly one provider",
  );
  rejects({ config_url: URL_OK, fallback_url: URL_OK }, "unknown key");
  rejects({ config_url: URL_OK, servers: [] }, "Servers come from that config");
  rejects([], "must be an object");
  rejects(null, "must be an object");
  rejects({}, "config_url is required");
  rejects({ config_url: 42 }, "config_url is required");
});

test("plaintext, credentialed and fragmented endpoints cannot be baked in", () => {
  for (const url of [
    "http://example.com/config.json",
    "ftp://example.com/config.json",
    "file:///etc/passwd",
    "javascript:alert(1)",
    "https://user:pass@example.com/config.json",
    "https://example.com/config.json#fragment",
    "not a url",
  ]) {
    assert.throws(
      () => validateConfigUrl(url),
      ProviderConfigError,
      `accepted ${url}`,
    );
  }
  assert.throws(
    () => validateConfigUrl(`https://example.com/${"a".repeat(2100)}`),
    /2048/,
  );
  assert.equal(validateConfigUrl(URL_OK), URL_OK);
  // Whitespace-only is the unconfigured template, not a bad URL.
  assert.equal(validateProvider({ config_url: "   " }).configUrl, "");
});

test("an installer cannot be built from an unconfigured template", () => {
  assert.throws(
    () => requireConfigured(validateProvider({ config_url: "" })),
    /before building an installer/,
  );
  // A configured project passes.
  requireConfigured(validateProvider({ config_url: URL_OK }));
  // The installer builder must actually call the guard.
  const builder = read("scripts/tauri-build.mjs");
  assert.match(builder, /"--require-provider"/);
  // The guard must run before any bundling pass, and abort on failure.
  const guard = builder.indexOf('"--require-provider"');
  assert.ok(guard < builder.indexOf("for (const pass of buildPasses"));
  assert.match(builder, /if \(provider\.status !== 0\) process\.exit/);
});

test("a configured build connects by itself and never asks for an address", () => {
  const configured = validateProvider({ config_url: URL_OK });
  assert.equal(isConfigured(configured), true);
  // Same in dev and in a release: one provider means no address screen.
  assert.equal(connectionMode(configured, false), "auto");
  assert.equal(connectionMode(configured, true), "auto");

  const template = validateProvider({ config_url: "" });
  // A developer working on the template may type an address...
  assert.equal(connectionMode(template, true), "dev-url");
  // ...but a shipped unconfigured build refuses rather than guessing.
  assert.equal(connectionMode(template, false), "unconfigured");
});

test("a configured build refuses a cached config from another address", () => {
  const configured = validateProvider({ config_url: URL_OK });
  assert.equal(isAllowedCachedUrl(configured, URL_OK), true);
  // Trailing slash and whitespace are the same address.
  assert.equal(isAllowedCachedUrl(configured, `  ${URL_OK}/  `), true);
  assert.equal(
    isAllowedCachedUrl(configured, "https://evil.test/config.json"),
    false,
  );
  assert.equal(
    isAllowedCachedUrl(configured, "http://example.com/line/config.json"),
    false,
  );
  assert.equal(isAllowedCachedUrl(configured, ""), false);
  // The unconfigured dev template keeps whatever the developer connected to.
  const template = validateProvider({ config_url: "" });
  assert.equal(isAllowedCachedUrl(template, "https://other.test/c.json"), true);
});

