//! Player settings, persisted in the per-user app-data directory.
//!
//! Deliberately narrow. The launch hardening in `launch.rs` rejects `-javaagent`
//! and classpath injection, so there is no free-form JVM argument field here:
//! the player picks a heap size and one of the Java runtimes the launcher itself
//! discovered or explicitly selected. A stored Java path is never trusted on
//! its own: Rust resolves it and executes `java -version` before saving/launch.
use super::error::{LineError, LineResult};
use super::launch::{heap_ceiling, validate_heap};
use super::storage::atomic_write;
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use tauri::{AppHandle, Manager};

pub const MIN_WINDOW_WIDTH: u32 = 800;
pub const MIN_WINDOW_HEIGHT: u32 = 560;
pub const MAX_WINDOW_DIMENSION: u32 = 15_360;

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
#[serde(rename_all = "lowercase")]
pub enum AfterLaunch {
    /// Leave the launcher window as it is.
    #[default]
    Keep,
    Minimize,
    Close,
    /// Hide the window and keep the process alive in the notification area.
    /// Unlike `Minimize` the window leaves the taskbar, so the game gets the
    /// whole screen; the tray icon is the way back.
    Tray,
}

/// Player-owned sections of the catalogue. See `LauncherSettings::server_layout`.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct ServerLayout {
    /// Named sections, in the order the player arranged them.
    pub sections: Vec<ServerSection>,
    /// server id -> section id. A server with no entry sits in "no section".
    pub assignments: std::collections::BTreeMap<String, String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ServerSection {
    /// Generated by the UI (`crypto.randomUUID`); never used as a path.
    pub id: String,
    pub name: String,
    pub collapsed: bool,
}

/// The catalogue's ceiling, mirroring `config::MAX_SERVERS`. A layout describes
/// servers from the provider, so it cannot be bigger than the catalogue.
pub const MAX_SECTIONS: usize = 32;
pub const MAX_SECTION_NAME: usize = 40;

impl ServerLayout {
    /// Structural checks only. Which server belongs where is *not* checked here:
    /// the provider changes its catalogue between launches, and a layout that
    /// mentions a server that no longer exists must lose that entry quietly
    /// rather than make the settings document invalid.
    pub fn validate(&self) -> LineResult<()> {
        if self.sections.len() > MAX_SECTIONS {
            return Err(LineError::input("Слишком много секций серверов."));
        }
        let mut ids = std::collections::HashSet::new();
        for section in &self.sections {
            if section.id.is_empty()
                || section.id.len() > 64
                || !ids.insert(&section.id)
                || section.name.trim().is_empty()
                || section.name.chars().count() > MAX_SECTION_NAME
                || section.name.chars().any(char::is_control)
            {
                return Err(LineError::input("Некорректная секция серверов."));
            }
        }
        let known: std::collections::HashSet<&str> =
            self.sections.iter().map(|s| s.id.as_str()).collect();
        if self
            .assignments
            .values()
            .any(|section| !known.contains(section.as_str()))
        {
            return Err(LineError::input("Сервер назначен в несуществующую секцию."));
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", default)]
pub struct LauncherSettings {
    /// None = derive from physical memory exactly as before.
    pub heap_mb: Option<u32>,
    /// Must match a runtime the launcher discovers; revalidated before launch.
    pub java_path: Option<String>,
    /// Persisted so the navigation stays the way the player left it.
    ///
    /// Defaults to collapsed: the new design is a 60px icon rail, and a first
    /// run that opens a 208px labelled sidebar immediately contradicts it.
    pub sidebar_collapsed: bool,
    pub after_launch: AfterLaunch,
    /// Backdrop theme id (`src/lib/line/backdrops.ts`). Stored as a plain
    /// string on purpose: the launcher validates it against the list it ships
    /// with, and an id it does not know falls back to the default instead of
    /// breaking the window. Keeping the list in one place (TypeScript) avoids
    /// two copies that drift.
    #[serde(default)]
    pub backdrop: Option<String>,
    /// Interface language (`ru`, `en`, `de`, `fr`). A plain string for the same
    /// reason as `backdrop`: the catalogue of languages lives in TypeScript, and
    /// an unknown code falls back to Russian rather than blanking the interface.
    /// `None` means "nobody has chosen yet": the UI then follows the system
    /// language, and Russian is only the floor when the system is neither `en`,
    /// `de` nor `fr`. Once a choice is stored it outranks the system.
    #[serde(default)]
    pub language: Option<String>,
    /// How the player grouped the server catalogue.
    ///
    /// The provider does not know about this: sections are the player's
    /// arrangement of *other people's* servers, so putting them in `config.json`
    /// would let a provider rename a folder the player made and reorder a list
    /// it does not own. Stored as an opaque document and validated loosely —
    /// a layout that does not fit is discarded, never a reason to fail startup.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub server_layout: Option<ServerLayout>,
    /// How the main panels are painted: `glass` (the animated backdrop shows
    /// through) or `solid` (opaque deep-charcoal panels). The backdrop itself
    /// remains unchanged in either finish.
    ///
    /// A plain string, like the backdrop id: the UI validates the two supported
    /// values and falls back to its default for an unknown one. `None` means the
    /// theme's own default, so changing that default does not rewrite settings.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub workspace: Option<String>,
    /// `live` animates the backdrop; `static` preserves its selected palette.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub backdrop_motion: Option<String>,
    /// Missing in legacy settings means onboarding was already completed.
    #[serde(default = "legacy_onboarding_complete")]
    pub onboarding_completed: bool,
    /// Whether the signed-in player has completed or skipped the guided tour.
    #[serde(default)]
    pub launcher_tour_completed: bool,
    /// Explicit opt-in for the provider's minimal telemetry. Defaults off.
    #[serde(default)]
    pub telemetry_consent: bool,
    /// Pack download cap in KiB/s; zero means unlimited.
    pub download_limit_kib: u32,
    pub window_width: u32,
    pub window_height: u32,
    pub window_maximized: bool,
}

fn legacy_onboarding_complete() -> bool {
    true
}

impl Default for LauncherSettings {
    fn default() -> Self {
        Self {
            heap_mb: None,
            java_path: None,
            sidebar_collapsed: true,
            after_launch: AfterLaunch::Keep,
            backdrop: None,
            language: None,
            server_layout: None,
            workspace: None,
            backdrop_motion: None,
            onboarding_completed: false,
            launcher_tour_completed: false,
            telemetry_consent: false,
            download_limit_kib: 0,
            window_width: 1100,
            window_height: 720,
            window_maximized: false,
        }
    }
}

impl LauncherSettings {
    /// Reject out-of-range values instead of silently clamping, so the UI and
    /// the stored document can never disagree about what was saved.
    pub fn validate(&self, total_memory_bytes: u64) -> LineResult<()> {
        if self.download_limit_kib > 1_048_576 {
            return Err(LineError::input("Недопустимый лимит загрузки."));
        }
        if let Some(heap) = self.heap_mb {
            validate_heap(heap, total_memory_bytes)?;
        }
        if let Some(path) = &self.java_path {
            super::java::validate_path(path)?;
        }
        if let Some(layout) = &self.server_layout {
            layout.validate()?;
        }
        if let Some(workspace) = &self.workspace {
            if workspace != "glass" && workspace != "solid" {
                return Err(LineError::input("Неизвестный вид рабочей зоны."));
            }
        }
        if let Some(motion) = &self.backdrop_motion {
            if motion != "static" && motion != "live" {
                return Err(LineError::input("Неизвестный режим движения фона."));
            }
        }
        if !(MIN_WINDOW_WIDTH..=MAX_WINDOW_DIMENSION).contains(&self.window_width)
            || !(MIN_WINDOW_HEIGHT..=MAX_WINDOW_DIMENSION).contains(&self.window_height)
        {
            return Err(LineError::input("Недопустимый размер окна."));
        }
        Ok(())
    }
}

fn settings_path(app: &AppHandle) -> LineResult<PathBuf> {
    Ok(app
        .path()
        .app_data_dir()
        .map_err(|_| LineError::storage())?
        .join("settings.json"))
}

/// A corrupt or unreadable document must not brick startup: fall back to
/// defaults. Values are still validated against this machine's memory.
pub fn load(app: &AppHandle, total_memory_bytes: u64) -> LauncherSettings {
    let Ok(path) = settings_path(app) else {
        return LauncherSettings::default();
    };
    let Ok(bytes) = std::fs::read(path) else {
        return LauncherSettings::default();
    };
    if bytes.len() > 64 * 1024 {
        return LauncherSettings::default();
    }
    match serde_json::from_slice::<LauncherSettings>(&bytes) {
        Ok(settings) if settings.validate(total_memory_bytes).is_ok() => settings,
        _ => LauncherSettings::default(),
    }
}

pub fn save(
    app: &AppHandle,
    settings: &LauncherSettings,
    total_memory_bytes: u64,
) -> LineResult<()> {
    settings.validate(total_memory_bytes)?;
    let bytes = serde_json::to_vec_pretty(settings).map_err(|_| {
        LineError::new(super::error::ErrorCode::Internal, "Ошибка настроек.", false)
    })?;
    atomic_write(&settings_path(app)?, &bytes)
}

pub fn init_download_limit(app: &AppHandle) {
    let settings = load(app, total_memory());
    super::download_limit::set_limit_kib(settings.download_limit_kib);
}

pub(crate) fn total_memory() -> u64 {
    let mut system = sysinfo::System::new();
    system.refresh_memory();
    system.total_memory()
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SettingsSnapshot {
    pub settings: LauncherSettings,
    pub heap_ceiling_mb: u32,
    pub suggested_heap_mb: u32,
    pub total_memory_mb: u32,
}

fn snapshot(settings: LauncherSettings, total: u64) -> SettingsSnapshot {
    SettingsSnapshot {
        settings,
        heap_ceiling_mb: heap_ceiling(total),
        suggested_heap_mb: super::launch::optimal_heap_mb(total),
        total_memory_mb: (total / (1024 * 1024)) as u32,
    }
}

#[tauri::command]
pub async fn get_settings(app: AppHandle) -> LineResult<SettingsSnapshot> {
    let total = total_memory();
    let settings = load(&app, total);
    super::download_limit::set_limit_kib(settings.download_limit_kib);
    Ok(snapshot(settings, total))
}

#[tauri::command]
pub async fn save_settings(
    app: AppHandle,
    mut settings: LauncherSettings,
) -> LineResult<SettingsSnapshot> {
    let total = total_memory();
    // An explicit path need not be on PATH/JAVA_HOME. Resolve and execute it
    // directly, then persist the canonical executable rather than the hint.
    if let Some(requested) = &settings.java_path {
        let runtime = super::java::inspect_path(requested).await?;
        settings.java_path = Some(runtime.path.to_string_lossy().into_owned());
    }
    save(&app, &settings, total)?;
    super::download_limit::set_limit_kib(settings.download_limit_kib);
    Ok(snapshot(settings, total))
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct JavaRuntimeInfo {
    pub path: String,
    pub major: u16,
    pub version: String,
}

/// Verifies a player-supplied java.exe/JDK path and returns actionable failure.
#[tauri::command]
pub async fn probe_java_path(path: String) -> LineResult<JavaRuntimeInfo> {
    let runtime = super::java::inspect_path(&path).await?;
    Ok(JavaRuntimeInfo {
        path: runtime.path.to_string_lossy().into_owned(),
        major: runtime.major,
        version: runtime.version,
    })
}

#[tauri::command]
pub async fn list_java_runtimes() -> LineResult<Vec<JavaRuntimeInfo>> {
    Ok(super::java::list_runtimes()
        .await
        .into_iter()
        .map(|r| JavaRuntimeInfo {
            path: r.path.to_string_lossy().into_owned(),
            major: r.major,
            version: r.version,
        })
        .collect())
}

/// Removes only the cached provider config. Installed builds and history live
/// under instances/ and are never touched by this command.
#[tauri::command]
pub async fn clear_config_cache(app: AppHandle) -> LineResult<bool> {
    let path = super::config_commands::cache_file_path(&app)?;
    match std::fs::remove_file(&path) {
        Ok(()) => Ok(true),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(LineError::io(&error)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn legacy_catalog_view_settings_are_ignored_and_removed_on_save() {
        // Older releases persisted `catalogView` as "grid" or "harmony".
        // Serde's default unknown-field behavior keeps those settings loadable;
        // the unified catalogue writes the retired preference out on next save.
        let settings: LauncherSettings = serde_json::from_str(
            r#"{"catalogView":"harmony","sidebarCollapsed":true}"#,
        )
        .unwrap();
        assert!(settings.validate(16 * 1024 * 1024 * 1024).is_ok());
        let serialized = serde_json::to_string(&settings).unwrap();
        assert!(!serialized.contains("catalogView"));
    }

    #[test]
    fn workspace_accepts_only_the_two_finishes_this_build_paints() {
        let total = 16 * 1024 * 1024 * 1024;
        for ok in [None, Some("glass"), Some("solid")] {
            assert!(
                LauncherSettings {
                    workspace: ok.map(str::to_string),
                    ..LauncherSettings::default()
                }
                .validate(total)
                .is_ok()
            );
        }
        assert!(
            LauncherSettings {
                workspace: Some("frosted".to_string()),
                ..LauncherSettings::default()
            }
            .validate(total)
            .is_err()
        );
    }


}
