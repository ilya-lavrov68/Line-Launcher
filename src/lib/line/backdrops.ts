/**
 * The catalogue key for a theme's name.
 *
 * Typed as an intersection with `string`, not as `` `backdrop.${string}` ``:
 * the letter would let any id through to the translator, including a stored
 * theme from a newer build that this one does not know. The picker only ever
 * passes ids from `BACKDROP_THEMES`, and the catalogue has one name per id —
 * `tests/i18n.test.ts` is what keeps the two lists in step.
 */
export type BackdropNameKey = `backdrop.${string}`;

export function backdropNameKey(id: string): BackdropNameKey {
  return `backdrop.${id}` as BackdropNameKey;
}

export function backdropTheme(id: string | null | undefined): BackdropTheme {
  return BACKDROP_THEMES.find((entry) => entry.id === id) ?? BACKDROP_THEMES[0];
}

/**
 * Where each stop sits in the CSS field, in the same normalised coordinates the
 * shader uses. Only the first five stops are positioned; a mesh config has up to
 * nine colours but the CSS stand-in keeps the palette's own five, because the
 * point of the fallback is the colour, not the geometry.
 */
const STOP_LAYOUT = [
  [16, 18, 120, 130],
  [84, 22, 115, 125],
  [50, 82, 125, 105],
  [86, 66, 90, 95],
  [14, 70, 95, 90],
] as const;

/**
 * The CSS stand-in for a theme, built from that theme's own palette and its own
 * shape.
 *
 * It is not a second design. It is the same picture painted without a GPU, and
 * it matters twice over: on a machine without WebGL2 this is the whole
 * backdrop, and in the settings preview each row paints it as the animated
 * thumbnail. Because both read `config.shape` and `config.palette`, a preview
 * can never show something the app will not render.
 *
 * Shape → layout:
 *   band  — two wide horizontal pools, the ramp read left to right;
 *   ring  — a bright pool with a dark core, which is what the shader draws;
 *   mesh  — one pool per mesh point, at the point's real position;
 *   pill / blob — the five stops spread around the centre point.
 *
 * It also differs from the old fallback in weight: the previous version mixed
 * four `transparent` stops over the canvas, which at preview size read as four
 * grey smudges. Here every stop keeps its colour and the canvas is a base layer,
 * so a 156x44 thumbnail has something to show.
 */
export function backdropField(theme: BackdropTheme): string {
  const { shape, palette, mesh, center } = theme.config;
  const stops = palette.slice(0, 5);
  const at = (i: number) => stops[i % stops.length];
  const pool = (x: number, y: number, w: number, h: number, colour: string) =>
    `radial-gradient(${w}% ${h}% at ${x}% ${y}%, ${colour} 0%, ${hexToRgba(colour, 0)} 100%)`;

  if (shape === "mesh" && mesh.length > 0) {
    const points = mesh
      .map(([x, y, colour]) => pool(x * 100, y * 100, 60, 60, colour))
      .join(",");
    return `${points}, linear-gradient(${theme.config.background}, ${theme.config.background})`;
  }

  if (shape === "band") {
    // Two heavy bands crossing the frame: the shader's band is a long ramp and
    // two bands at 20% and 78% carry that direction without a seam.
    return [
      pool(18, 16, 150, 85, at(1)),
      pool(72, 46, 140, 90, at(2)),
      pool(30, 84, 130, 80, at(3)),
      pool(88, 88, 110, 70, at(4)),
      `linear-gradient(${theme.config.background}, ${theme.config.background})`,
    ].join(",");
  }

  if (shape === "ring") {
    // A bright annulus needs a hole: the core is the canvas colour, not a stop.
    const [cx, cy] = center;
    return [
      pool(cx * 100, cy * 100, 78, 74, at(1)),
      pool(cx * 100, cy * 100, 34, 32, theme.config.background),
      pool(20, 80, 75, 75, at(2)),
      pool(88, 30, 70, 70, at(3)),
      `linear-gradient(${theme.config.background}, ${theme.config.background})`,
    ].join(",");
  }

  // pill and blob: the five stops laid out around the shape's centre.
  const [cx, cy] = center;
  return [
    ...STOP_LAYOUT.map(([dx, dy, w, h], index) =>
      pool(
        cx * 100 + (dx - 50) * 0.9,
        cy * 100 + (dy - 50) * 0.9,
        w,
        h,
        at(index),
      ),
    ),
    `linear-gradient(${theme.config.background}, ${theme.config.background})`,
  ].join(",");
}

/** `#rrggbb` → `rgba()` so a stop can fade to transparent without a hard edge. */
function hexToRgba(hex: string, alpha: number): string {
  const value = hex.replace("#", "");
  const full =
    value.length === 3
      ? value
          .split("")
          .map((c) => c + c)
          .join("")
      : value;
  const r = parseInt(full.slice(0, 2), 16);
  const g = parseInt(full.slice(2, 4), 16);
  const b = parseInt(full.slice(4, 6), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}
