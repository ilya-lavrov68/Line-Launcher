import type { GradientConfig } from "hazeglow";

/**
 * Backdrop themes.
 *
 * Every config in this file came out of hazeglow's own randomizer — the
 * `randomConfig(seed)` export, which is the function behind the "Randomize"
 * button at hazeglow.dev/generator. That is why they no longer look like twelve
 * filters over one picture: the generator picks a palette family, then a shape,
 * a size, a warp and a grain amount from that seed, so a pill in dusk and a
 * ring in ultraviolet are different objects, not different hues of one object.
 *
 * Do not hand-tune these. If a theme looks wrong, take it back to the generator,
 * randomize until it is right and paste the config — an edit made by hand here
 * is an edit the generator cannot reproduce, which is exactly how the previous
 * set drifted into looking alike.
 *
 * The only field this file overrides is `speed`: the generator tunes motion for
 * a hero band a few hundred pixels tall, and this canvas is a whole window seen
 * for minutes, so every theme runs at 1.1.
 *
 * ## Why `shade`
 *
 * The haze is decoration behind glass, but the title bar sits *on* it. A bright
 * ramp lifts the top of the window enough that the caption buttons and the brand
 * mark lose contrast, which is what a pale gradient did in the first pass of
 * this design. `shade` is the opacity of the `bg-background` veil painted over
 * everything: dark themes need almost none, bright ones need nearly half the
 * screen. It is a property of the theme, not a global constant, because one
 * value that keeps a white gradient readable turns a navy one into black.
 */

export interface BackdropTheme {
  id: string;
  name: string;
  /**
   * Three colours that read as the theme at thumbnail size, picked from its own
   * palette: the dominant warm, the dominant cool and a mid-tone between them.
   * They paint the preview and the swatch, never anything else.
   */
  swatch: [string, string, string];
  /** Opacity of the legibility veil over the haze. 0 = none, 1 = opaque. */
  shade: number;
  config: GradientConfig;
}

